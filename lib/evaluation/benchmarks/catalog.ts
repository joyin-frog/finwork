export const BENCHMARK_DATASET_CATALOG = Object.freeze(
  rawCatalog.map((descriptor) => BenchmarkDatasetDescriptorSchema.parse(descriptor)),
);

const catalogById = new Map(BENCHMARK_DATASET_CATALOG.map((descriptor) => [descriptor.id, descriptor]));

export function getBenchmarkDatasetDescriptor(id: BenchmarkDatasetId): BenchmarkDatasetDescriptor {
  const descriptor = catalogById.get(id);
  if (!descriptor) throw new Error(`unknown benchmark dataset: ${id}`);
  return descriptor;
}

export function listBenchmarkDatasetDescriptors(): readonly BenchmarkDatasetDescriptor[] {
  return BENCHMARK_DATASET_CATALOG;
}
